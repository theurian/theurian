#!/usr/bin/env bash
# Shared helpers for Theurian plugin scripts.
#
# These scripts are thin adapters over the `theurian` CLI. They contain no
# Theurian logic -- version comparison, setup planning, and health semantics all
# live in Core, and are reached through published commands (CP-2, CP-7, §34).
#
# Nothing here may import or execute Python from the Theurian package.

set -euo pipefail

THEURIAN_DEFAULT_HOST="127.0.0.1"
THEURIAN_DEFAULT_PORT="7419"
THEURIAN_HEALTH_TIMEOUT_SECONDS="2"

# Exit code Core uses for a compatibility mismatch, distinct from a generic
# failure so a caller can tell them apart.
#
# shellcheck disable=SC2034  # consumed by scripts that source this file
THEURIAN_EXIT_INCOMPATIBLE=3

theurian::plugin_root() {
  printf '%s\n' "${CLAUDE_PLUGIN_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
}

# Is the Theurian CLI available?
theurian::cli_present() {
  command -v theurian >/dev/null 2>&1
}

# Read one key from the plugin's compatibility.yaml.
#
# Deliberately a narrow line-oriented reader rather than a YAML parser: the file
# is generated by this repository and validated in CI against
# schemas/protocol/compatibility.schema.json, and adding a YAML dependency to a
# hook that must finish in milliseconds is not a trade worth making.
theurian::compat_value() {
  local key="$1"
  local file
  file="$(theurian::plugin_root)/compatibility.yaml"
  [ -f "$file" ] || return 1
  sed -n -E "s/^[[:space:]]*${key}:[[:space:]]*([^[:space:]#]+).*/\1/p" "$file" | head -n 1
}

# Ask Core whether this plugin may operate against it.
#
# Core owns the comparison. The plugin only supplies its declaration and reads
# the verdict, so SemVer ordering and the PEP 440 translation exist in exactly
# one place.
#
# Echoes the JSON verdict. Returns 0 compatible, 3 incompatible, 1 CLI absent.
theurian::compat_check() {
  theurian::cli_present || return 1
  theurian compat check \
    --plugin-version "$(theurian::compat_value pluginVersion)" \
    --core-minimum "$(theurian::compat_value minimum)" \
    --core-maximum-exclusive "$(theurian::compat_value maximumExclusive)" \
    --protocol-version "$(theurian::compat_value protocolVersion)" \
    --json
}

# Probe the daemon's unauthenticated health endpoint.
#
# Unauthenticated by design (ADR-0011): a health check must not need a
# credential, which is what lets SessionStart stay fast and unprivileged.
theurian::daemon_healthy() {
  local host="${THEURIAN_HOST:-$THEURIAN_DEFAULT_HOST}"
  local port="${THEURIAN_PORT:-$THEURIAN_DEFAULT_PORT}"
  curl --silent --show-error --fail \
    --max-time "$THEURIAN_HEALTH_TIMEOUT_SECONDS" \
    "http://${host}:${port}/health" >/dev/null 2>&1
}

theurian::warn() {
  printf 'Theurian: %s\n' "$*" >&2
}
